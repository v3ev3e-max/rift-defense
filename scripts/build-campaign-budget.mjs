import {readFileSync,writeFileSync} from 'node:fs';
const rows=JSON.parse(readFileSync('artifacts/hero-budget-after.json','utf8'));
const result={};
for(const row of rows.filter(r=>r.auto&&r.targets===1)){
 const basic=rows.find(r=>r.id===row.id&&!r.auto&&r.targets===1);
 const crowd=rows.find(r=>r.id===row.id&&r.auto&&r.targets===3);
 result[row.id]={attack:row.atk,speed:row.speed,singleDps:+row.dps.toFixed(3),basicDps:+basic.dps.toFixed(3),crowdDps:+crowd.dps.toFixed(3)};
}
writeFileSync('src/data/campaignCombatBudget.ts','// Generated by scripts/build-campaign-budget.mjs from the 30-second combat audit.\nexport const campaignCombatBudget:Record<string,{attack:number;speed:number;singleDps:number;basicDps:number;crowdDps:number}>='+JSON.stringify(result,null,2)+';\n');
